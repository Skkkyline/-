# -*- coding: utf-8 -*-
"""
Plot Chinese figures for Himawari causal ablation results.

Expected inputs generated by summarize_himawari_causal_results_fixed.py:
    results/paper_tables/table_himawari_causal_mean_by_horizon_fixed.csv
    results/paper_tables/table_himawari_site_improvement_vs_era5_fixed.csv

Usage:
    python src/plot_himawari_causal_results.py --root .
"""
from pathlib import Path
import argparse
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

LABELS = {
    "persistence": "持续性基线",
    "power_only": "历史功率",
    "power_weather": "历史功率+地面气象",
    "power_weather_era5": "历史功率+地面气象+ERA5",
    "power_weather_himawari": "历史功率+地面气象+Himawari",
    "power_weather_era5_himawari": "历史功率+地面气象+ERA5+Himawari",
}
ORDER = [
    "persistence",
    "power_only",
    "power_weather",
    "power_weather_era5",
    "power_weather_himawari",
    "power_weather_era5_himawari",
]


def setup_font():
    plt.rcParams["font.sans-serif"] = ["Microsoft YaHei", "SimHei", "Arial Unicode MS", "DejaVu Sans"]
    plt.rcParams["axes.unicode_minus"] = False


def plot_nrmse_bar(mean_df, out_dir):
    horizons = [15, 30, 60]
    x = np.arange(len(horizons))
    width = 0.13
    fig, ax = plt.subplots(figsize=(12, 6), dpi=200)

    for i, fs in enumerate(ORDER):
        vals = []
        for h in horizons:
            sub = mean_df[(mean_df["horizon_min"] == h) & (mean_df["feature_set"] == fs)]
            vals.append(float(sub["nRMSE_pct"].iloc[0]) if len(sub) else np.nan)
        ax.bar(x + (i - (len(ORDER)-1)/2) * width, vals, width, label=LABELS.get(fs, fs))

    ax.set_xticks(x)
    ax.set_xticklabels([f"{h} min" for h in horizons])
    ax.set_xlabel("预测步长")
    ax.set_ylabel("nRMSE / %")
    ax.set_title("融合 Himawari 特征前后的九站点平均 nRMSE 对比")
    ax.grid(axis="y", linestyle="--", alpha=0.35)
    ax.legend(ncol=2, fontsize=9)
    fig.tight_layout()
    fig.savefig(out_dir / "图_Himawari因果消融_nRMSE对比.png", bbox_inches="tight")
    plt.close(fig)


def plot_improvement_line(imp_df, out_dir):
    sub = imp_df[imp_df["feature_set"].isin(["power_weather_himawari", "power_weather_era5_himawari"])].copy()
    horizons = [15, 30, 60]
    fig, ax = plt.subplots(figsize=(9, 5), dpi=200)

    for fs in ["power_weather_himawari", "power_weather_era5_himawari"]:
        vals = []
        for h in horizons:
            row = sub[(sub["horizon_min"] == h) & (sub["feature_set"] == fs)]
            vals.append(float(row["nrmse_improve_vs_era5_pct"].iloc[0]) if len(row) else np.nan)
        ax.plot([f"{h} min" for h in horizons], vals, marker="o", label=LABELS.get(fs, fs))

    ax.axhline(0, linestyle="--", linewidth=1)
    ax.set_xlabel("预测步长")
    ax.set_ylabel("相对 ERA5 组合的 nRMSE 改善率 / %")
    ax.set_title("引入 Himawari 后的相对误差变化")
    ax.grid(True, linestyle="--", alpha=0.35)
    ax.legend()
    fig.tight_layout()
    fig.savefig(out_dir / "图_Himawari相对ERA5_nRMSE改善率.png", bbox_inches="tight")
    plt.close(fig)


def plot_site_heatmap(site_df, out_dir):
    sub = site_df[site_df["feature_set"] == "power_weather_era5_himawari"].copy()
    pivot = sub.pivot(index="user", columns="horizon_min", values="nrmse_improve_pct").sort_index()
    fig, ax = plt.subplots(figsize=(7, 5), dpi=200)
    im = ax.imshow(pivot.values, aspect="auto")
    ax.set_xticks(np.arange(len(pivot.columns)))
    ax.set_xticklabels([f"{int(c)} min" for c in pivot.columns])
    ax.set_yticks(np.arange(len(pivot.index)))
    ax.set_yticklabels(pivot.index)
    ax.set_xlabel("预测步长")
    ax.set_ylabel("站点")
    ax.set_title("ERA5+Himawari 相对 ERA5 的 nRMSE 改善率 / %")

    for i in range(pivot.shape[0]):
        for j in range(pivot.shape[1]):
            ax.text(j, i, f"{pivot.values[i, j]:.1f}", ha="center", va="center", fontsize=9)
    fig.colorbar(im, ax=ax, label="nRMSE 改善率 / %")
    fig.tight_layout()
    fig.savefig(out_dir / "图_Himawari站点_nRMSE改善率热力图.png", bbox_inches="tight")
    plt.close(fig)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=Path("."))
    args = parser.parse_args()
    setup_font()

    table_dir = args.root / "results" / "paper_tables"
    out_dir = args.root / "results" / "figures_himawari"
    out_dir.mkdir(parents=True, exist_ok=True)

    mean_path = table_dir / "table_himawari_causal_mean_by_horizon_fixed.csv"
    imp_path = table_dir / "table_himawari_causal_improvement_vs_era5_fixed.csv"
    site_path = table_dir / "table_himawari_site_improvement_vs_era5_fixed.csv"

    mean_df = pd.read_csv(mean_path)
    imp_df = pd.read_csv(imp_path)
    site_df = pd.read_csv(site_path)

    plot_nrmse_bar(mean_df, out_dir)
    plot_improvement_line(imp_df, out_dir)
    plot_site_heatmap(site_df, out_dir)
    print("[OK] figures saved to", out_dir)


if __name__ == "__main__":
    main()
